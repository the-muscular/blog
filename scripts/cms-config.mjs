// Writes .pages.yml (the Pages CMS editor config) from the doodle library,
// so the Illustration / Colour / Topic dropdowns always match the site.
// Run with: npm run cms-config
import { writeFileSync } from 'node:fs';
import { doodles, doodleGroups, colours, topics, topicNames } from '../src/lib/doodles.mjs';

const q = (s) => JSON.stringify(s);
const options = (pairs, indent) =>
  pairs.map(([name, label]) => `${indent}- name: ${q(name)}\n${indent}  label: ${q(label)}`).join('\n');

const doodleOptions = doodleGroups.flatMap(([group, keys]) => keys.map((k) => [k, `${group} · ${doodles[k].name}`]));
const defaults = topicNames.map((t) => `${t}: ${doodles[topics[t].doodle].name}`).join(', ');

const networks = ['instagram', 'twitter', 'x','linkedin', 'pinterest', 'tiktok', 'youtube', 'spotify', 'letterboxd', 'email', 'website'];

const yml = `# Pages CMS config (https://pagescms.org). Generated by scripts/cms-config.mjs — edit that script, not this file.
media:
  input: public/images
  output: /images

content:
  - name: posts
    label: Posts
    type: collection
    path: src/content/posts
    filename: "{primary}.md"
    view:
      fields: [title, topic, date, draft]
      primary: title
      sort: [date, title]
      default:
        sort: date
        order: desc
    fields:
      - name: title
        label: Title
        type: string
        required: true
      - name: date
        label: Date
        type: date
        required: true
      - name: topic
        label: Topic
        type: select
        required: true
        options:
          values: ${q(topicNames)}
      - name: excerpt
        label: Excerpt
        description: Optional. One or two sentences for the post card. Leave empty to use the start of the post.
        type: text
      - name: doodle
        label: Cover illustration
        description: ${q(`Optional. Leave empty for the topic's default (${defaults}). See them all on your site at /covers/`)}
        type: select
        options:
          values:
${options(doodleOptions, '            ')}
      - name: colour
        label: Cover colour
        description: Optional. Leave empty for the topic's default colour.
        type: select
        options:
          values:
${options(colours, '            ')}
      - name: cover_image
        label: Cover photo
        description: Optional. Replaces the illustration with a photo. Most posts don't need one.
        type: image
      - name: draft
        label: Draft
        description: Drafts are saved but don't appear on the live site.
        type: boolean
        default: false
      - name: body
        label: Post
        type: rich-text

  - name: settings
    label: Site settings
    type: file
    path: src/data/site.json
    format: json
    fields:
      - name: title
        label: Blog title
        description: The last word gets the italic squiggle treatment.
        type: string
        required: true
      - name: kicker
        label: Small line above the title
        type: string
      - name: intro
        label: Intro under the title
        type: text
      - name: author
        label: Your name
        type: string
      - name: bio
        label: Short bio in the sidebar
        type: text
      - name: sticker
        label: Note under your links
        type: string
      - name: socials
        label: Social links
        type: object
        list: true
        fields:
          - name: network
            label: Network
            type: select
            options:
              values: ${q(networks)}
          - name: url
            label: Link
            description: Full address, e.g. https://instagram.com/yourname, or mailto:you@example.com for email.
            type: string
          - name: handle
            label: Handle shown next to the link
            type: string
`;

writeFileSync(new URL('../.pages.yml', import.meta.url), yml);
console.log(`Wrote .pages.yml with ${doodleOptions.length} illustrations, ${colours.length} colours, ${topicNames.length} topics.`);
